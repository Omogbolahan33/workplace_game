/*
  @ledger/ui — everything that draws, and the seam that lets an app own it.

  The screens are the imperative markup builders this game has always had:
  render(), the tabs, the views, the modal, the toasts. They read the simulation
  from @ledger/core through the host, and they own the DOM, the storage and the
  clipboard, which is exactly what core is not allowed to touch.

  Two things an app does:

      import './boot-flag.js';            // sets __LEDGER_IS_APP__ = true, FIRST
      import { install, boot, VIEWS } from '@ledger/ui';
      install();                          // the host can draw now
      boot();                             // restore the save, and draw

  A React app does that inside a client component that has a container in the
  document; React Native supplies its own host implementations and does not
  import this package at all.

  Screens are converted one at a time: core asks for a screen by name through
  host.view(name), so any name can be answered by React instead of by the
  markup builder without core knowing, or caring.
*/
import { installHost, host, routeViewInner, routeKey, ROUTE_GROUPS } from '@ledger/core';

/* One import, and it is generated.

   This file used to name eighteen module files directly:
   `./modules/01-working-capital-on-screen-the-cycle-is.js` and so on. That is
   a table of names that can fall out of step with reality, and it did: the
   section files were renamed, the modules were regenerated under their new
   names, and the app died with a module-not-found thrown from this file -
   while the single-file build, which never loads an ES module, stayed green
   and said everything was fine.

   registry.js already holds every export of every module, merged, generated by
   tools/tomodules.mjs from what is actually on disk. So nothing here names a
   file. Renaming a section now changes the registry and nothing else.
*/
