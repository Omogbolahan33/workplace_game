/* What the build promises, tested as a contract rather than as a gate.

   The gates assert these same facts in the language of "drift did not happen". A
   test states them as the promises they are, so a person reading a CI run can see
   what the repository actually commits to:

     * the game in the store build is the game in the zip, byte for byte
     * the zip holds ten files and its index.html is the composed one
     * every face on every platform is the mark in `ledger/icon.svg`
     * `tools/mobile.mjs` is idempotent and deletes what is no longer the game
 */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const { ROOT, sha, short } = require('../helpers/env.js');
const png = require(path.join(ROOT, '.harness', 'png.js'));

const at = (...p) => path.join(ROOT, ...p);
const ledger = at('ledger');
const ledgerFiles = fs.readdirSync(ledger).filter((f) => fs.statSync(path.join(ledger, f)).isFile()).sort();

/* A fresh clone has no `dist/` (it is generated, and gitignored) and no
   `node_modules/@ledger` links until an install creates them. Both used to surface
   as an ENOENT from six assertions deep, which reads like a broken test rather
   than a missing step — so the suite says the step. */
test('before anything: the build and the workspace links are here', () => {
  assert.ok(fs.existsSync(path.join(ROOT, 'dist', 'index.html')),
    'there is no dist/index.html — run `npm run build` (this suite asserts the built payload, it cannot invent it)');
  assert.ok(fs.existsSync(path.join(ROOT, 'node_modules', '@ledger', 'core')),
    'the workspace is not linked — run `npm install` at the repository root, which is what makes `@ledger/core` resolvable by name');
});

test('the shipped payload is ten files, and the game among them is the composed one', () => {
  assert.equal(ledgerFiles.length, 10, 'the zip ships ten files, found ' + ledgerFiles.length + ': ' + ledgerFiles.join(', '));
  for (const need of ['index.html', 'manifest.webmanifest', 'sw.js', 'icon.svg',
    'icon-192.png', 'icon-512.png', 'icon-maskable-512.png', 'apple-touch-icon.png']) {
    assert.ok(ledgerFiles.includes(need), 'the payload has no ' + need);
  }
  const composed = fs.readFileSync(at('dist', 'index.html'));
  const shipped = fs.readFileSync(path.join(ledger, 'index.html'));
  assert.equal(sha(shipped), sha(composed),
    'the file in the zip is not the file the build composed — `npm run build` and ship again');
  /* A bound rather than a byte count: the claim worth defending is that the
     deliverable did not balloon, and the exact figure is in the build's own log
     and in FEATURES. A number that has to be edited on every CSS change is a
     number that gets edited without being read. */
  assert.ok(shipped.length > 900000 && shipped.length < 1400000,
    'the shipped game is ' + shipped.length + ' bytes — out of the band it has held all year (0.9–1.4 MB)');
  console.log('  the shipped game is ' + shipped.length + ' bytes');
});

test('every copy of the game is the same bytes: zip, phone, mobile app, native project', () => {
  const shipped = fs.readFileSync(path.join(ledger, 'index.html'));
  const copies = [
    at('apps', 'phone', 'www', 'index.html'),
    at('apps', 'mobile', 'assets', 'game', 'index.html'),
  ];
  /* the native project's synced copy is generated by `cap add` + `npm run sync`
     and is not in a fresh checkout — compared when it is here, named when it is
     not, never silently skipped */
  const nativeCopy = at('apps', 'phone', 'android', 'app', 'src', 'main', 'assets', 'public', 'index.html');
  if (fs.existsSync(nativeCopy)) copies.push(nativeCopy);
  else console.log('  no native project in this tree — the Android copy is generated (`cap add android` + `npm run sync`)');
  for (const c of copies) {
    assert.ok(fs.existsSync(c), 'a copy of the game is missing: ' + path.relative(ROOT, c));
    assert.equal(sha(fs.readFileSync(c)), sha(shipped),
      path.relative(ROOT, c) + ' is a different game from the one in the zip');
  }
});

test('the build stamp describes the bytes it is stamped against', () => {
  const shipped = fs.readFileSync(path.join(ledger, 'index.html'));
  for (const rel of [['apps', 'phone', 'www'], ['apps', 'mobile', 'assets', 'game']]) {
    const stamp = JSON.parse(fs.readFileSync(at(...rel, 'build.json'), 'utf8'));
    assert.equal(stamp.game.sha, short(shipped), path.relative(ROOT, at(...rel)) + ' is stamped for another build');
    assert.equal(stamp.game.bytes, shipped.length);
    assert.ok(stamp.files >= 10);
  }
});

test('the zip is ten files, fresh, and contains the shipped payload', () => {
  const zip = at('ledger-app.zip');
  assert.ok(fs.existsSync(zip), 'there is no zip — run `npm run build`');
  const listing = execFileSync('unzip', ['-l', zip], { encoding: 'utf8' });
  /* `unzip -l` prints size, date, name — one line per file, plus headers. The
     date is YYYY-MM-DD from Info-ZIP on Linux and MM-DD-YYYY from the one macOS
     ships, and a listing that matched neither counted zero files on a Mac */
  const entries = listing.split('\n').filter((l) => /^\s*\d+\s+(\d{4}-\d{2}-\d{2}|\d{2}-\d{2}-\d{4})/.test(l));
  assert.equal(entries.length, 10, 'the zip holds ' + entries.length + ' files, not ten');
  /* and it is not older than what it was built from */
  assert.ok(fs.statSync(zip).mtimeMs >= fs.statSync(path.join(ledger, 'index.html')).mtimeMs,
    'the zip is older than the game inside it — the download is a lie');
  for (const f of ledgerFiles) assert.ok(listing.includes(f), 'the zip is missing ' + f);
});

test('every face on every platform is the mark, measured', () => {
  const mark = png.signature(fs.readFileSync(path.join(ledger, 'icon-512.png')));
  const faces = [
    [path.join(ledger, 'icon-192.png'), 'the PWA icon'],
    [path.join(ledger, 'icon-512.png'), 'the PWA icon, large'],
    [path.join(ledger, 'apple-touch-icon.png'), 'the iOS home screen icon'],
    [at('apps', 'phone', 'www', 'icon-512.png'), 'the store build’s icon'],
    [at('apps', 'mobile', 'assets', 'icon.png'), 'the React Native icon'],
    [at('apps', 'mobile', 'assets', 'game', 'icon-512.png'), 'the bundled app icon'],
    [at('apps', 'phone', 'resources', 'icon.png'), 'the master'],
  ];
  for (const [p, what] of faces) {
    assert.ok(fs.existsSync(p), what + ' is missing');
    const d = png.distance(png.signature(fs.readFileSync(p)), mark);
    assert.ok(d <= 30, what + ' is not the game’s mark (distance ' + d.toFixed(1) + ')');
  }
});

test('the adaptive icon is the mark alone, on the app’s colour, inside the safe zone', () => {
  const plate = fs.readFileSync(at('apps', 'mobile', 'assets', 'adaptive-icon.png'));
  const sig = png.signature(plate);
  assert.ok(png.coverage(sig) < 0.6,
    'an adaptive foreground is ' + Math.round(png.coverage(sig) * 100) + '% drawn — the launcher crops the outside of that');
  const nativeForeground = at('apps', 'phone', 'android', 'app', 'src', 'main', 'res', 'mipmap-xxxhdpi', 'ic_launcher_foreground.png');
  if (!fs.existsSync(nativeForeground)) {
    console.log('  the Android foreground is not in this tree (android/ is generated) — the master above is the same drawing');
    return;
  }
  assert.ok(png.coverage(png.signature(fs.readFileSync(nativeForeground))) < 0.6,
    'the Android adaptive foreground has its plate drawn');
});

test('the launcher icons are 48/72/96/144/192 across five densities, round included', (t) => {
  const res = at('apps', 'phone', 'android', 'app', 'src', 'main', 'res');
  if (!fs.existsSync(res)) return t.skip('android/ is generated and not in this tree — `npx cap add android` writes it where the SDK is');
  const want = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
  for (const [d, size] of Object.entries(want)) {
    for (const flavour of ['ic_launcher.png', 'ic_launcher_round.png']) {
      const p = path.join(res, 'mipmap-' + d, flavour);
      const sig = png.signature(fs.readFileSync(p));
      assert.equal(sig.width, size, 'mipmap-' + d + '/' + flavour + ' should be ' + size + 'px');
    }
  }
});

test('the splash screens are dark in every orientation and density', (t) => {
  const res = at('apps', 'phone', 'android', 'app', 'src', 'main', 'res');
  if (!fs.existsSync(res)) return t.skip('android/ is generated and not in this tree');
  const dirs = fs.readdirSync(res).filter((d) => /^drawable/.test(d) && fs.existsSync(path.join(res, d, 'splash.png')));
  assert.ok(dirs.length >= 11, 'the splash set covers both orientations and five densities, found ' + dirs.length);
  for (const d of dirs) {
    const sig = png.signature(fs.readFileSync(path.join(res, d, 'splash.png')));
    assert.equal(png.hex(sig.grid[0]).toLowerCase(), '#080b10',
      d + '/splash.png is not the app’s colour — a bright splash on a dark game flashes');
  }
});

test('the payload copier is idempotent and says so', () => {
  /* Running the build's copier again must change nothing: it copies byte for
     byte, and reports the hash it verified rather than trusting the clock. */
  const out = execFileSync('node', [at('tools', 'mobile.mjs')], { encoding: 'utf8', cwd: ROOT });
  assert.match(out, /byte for byte/, 'the copier did not report its verification: ' + out.split('\n')[0]);
  const again = execFileSync('node', [at('tools', 'mobile.mjs')], { encoding: 'utf8', cwd: ROOT });
  assert.equal(out.replace(/\d+ms/g, ''), again.replace(/\d+ms/g, ''), 'a second run reported something different');
});
