/*
  Assemble packages/core/core.js — the simulation as one module.

  Why one module: the simulation is one system. Split into 32 files it has 50
  import cycles, and the cycles are not accidents of layout - business
  capacity reads market conditions reads the era reads the economy reads
  business capacity. Modern bundlers cope; the point is that a file boundary
  there would be a claim about the code that the code does not make. The
  sections stay as readable, ordered files under src/; what ships and what the
  apps import is their concatenation, with the host seam in front of it.

  Splitting the simulation internally is a real refactor - untangling shared
  mutable state - and it is not something a mechanical pass can do. Splitting
  the *package* (this, from @ledger/ui) is different, and that part is done.

  The file is generated: edit the sections in src/ or the host in
  packages/core/host.js, then run tools/rebuild.sh.

  Run: node tools/makecore.mjs
*/
import fs from 'node:fs';
import path from 'node:path';
import * as acorn from 'acorn';
import { splice } from './tables.mjs';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');

/* The sections, in file order. split.mjs wrote them in the order it met their
   statements, so their filenames sort into the order they ran in, and that is
   the only ordering this file needs. (Reading them by recorded statement
   offsets instead was the earlier design; an offset is wrong the moment
   somebody edits the file it points into.) */
const coreFiles = fs.readdirSync(path.join(ROOT, 'packages', 'core', 'src'))
  .filter(f => f.endsWith('.js')).sort();
/* the data tables are spliced back from packages/core/tables, so the module and
   the single file are built from the same text */
const coreStatements = coreFiles.map(f => splice(read('packages/core/src/' + f), 'packages/core/src/' + f)).join('');

/* the host, without its own export keywords - the export block at the end
   covers everything in the file uniformly */
const host = read('packages/core/host.js')
  .split('\n').map(l => l.replace(/^export /, '')).join('\n');

/* the shims, without their import of the host (same file now) */
const shims = fs.existsSync(path.join(ROOT, 'packages/core/host-shims.js'))
  ? read('packages/core/host-shims.js')
      .split('\n').filter(l => !/^import /.test(l))
      .map(l => l.replace(/^export /, '')).join('\n').replace(/^\s*\n/, '')
  : '';

const body = `"use strict";
/* =========================================================================
   Ledger — the simulation, as one module.

   GENERATED by tools/makecore.mjs from the sections in src/. Do not edit this
   file; edit the section that owns the code and run tools/rebuild.sh.

   Nothing here touches the DOM, storage, or the network. Everything it needs
   from outside arrives through the host object at the top, which an app
   installs before the first quarter runs. See packages/core/host.js.
   ========================================================================= */

${host}

/* -------------------------------------------------------------------------
   The calls that leave the simulation, answered by the host above:
   ${shims.split('\n').filter(l => /^function /.test(l)).length} screens, redraws, toasts and services.
   ------------------------------------------------------------------------- */
${shims}

/* =========================================================================
   The sections, in the order they were written. This is the order they run
   in, and the order they have always run in.
   ========================================================================= */
${coreStatements}`;

/* export every top-level declaration, so an app can reach any of it */
const ast = acorn.parse(body, { ecmaVersion: 2022, locations: true });
const names = [];
for (const n of ast.body) {
  if (n.type === 'FunctionDeclaration' || n.type === 'ClassDeclaration') {
    if (n.id) names.push(n.id.name);
  } else if (n.type === 'VariableDeclaration') {
    for (const d of n.declarations) {
      const collect = x => {
        if (!x) return;
        if (x.type === 'Identifier') names.push(x.name);
        else if (x.type === 'ObjectPattern') x.properties.forEach(p => collect(p.value || p.argument));
        else if (x.type === 'ArrayPattern') x.elements.forEach(collect);
      };
      collect(d.id);
    }
  }
}
const uniq = [...new Set(names)].sort();
const out = body + `
/* -------------------------------------------------------------------------
   Everything above, exported. ${uniq.length} names: the simulation's whole surface.
   ------------------------------------------------------------------------- */
export {
${uniq.map(n => '  ' + n).join(',\n')}
};
`;
fs.writeFileSync(path.join(ROOT, 'packages/core/core.js'), out);
/* what this package offers, for whoever consumes it — the ui package imports
   by name and refuses to guess */
const exportMap = {};
for (const n of uniq) exportMap[n] = 'core.js';
fs.writeFileSync(path.join(ROOT, 'packages/core/exports.json'), JSON.stringify(exportMap, null, 1));
console.log('core.js           : ' + out.length.toLocaleString() + ' chars · ' +
  uniq.length + ' exported names · ' + coreStatements.split('\n').length.toLocaleString() +
  ' lines across ' + coreFiles.length + ' sections');
