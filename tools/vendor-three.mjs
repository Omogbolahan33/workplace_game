/*
  Build the one third-party library the game carries: the slice of three.js the
  3D world draws with.

    node tools/vendor-three.mjs           write packages/ui/vendor/three-world.js
    node tools/vendor-three.mjs --check   fail if the committed file is stale

  Why a committed file and not a build step: the game is one HTML file that opens
  with no network, and `npm run build` must stay byte-identical on a fresh
  checkout. So the library is built here, once, from an exact version, and the
  output is committed beside the sections; tools/compose.mjs splices it into the
  page as an inert <script type="text/plain"> that the world evaluates the first
  time it is shown. The game script never sees it, the statement ledger never
  reads it, and a player who never opens the world never pays for parsing it.

  Only what the world uses is imported, so esbuild can leave the rest of three.js
  behind. Add a name here before using it in packages/ui/src/*-world.js.
*/
import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const ROOT = path.join(import.meta.dirname, '..');
const OUT = path.join(ROOT, 'packages/ui/vendor/three-world.js');
/* the same text as a module whose default export is the string: the React page
   imports it like any module, so the app needs no Node API to inline it (its
   tsconfig keeps Node's types out on purpose) */
const OUT_MODULE = path.join(ROOT, 'packages/ui/vendor/three-world.text.mjs');
const PKG = JSON.parse(fs.readFileSync(path.join(import.meta.dirname, 'node_modules/three/package.json'), 'utf8'));

const NAMES = [
  'Scene', 'Color', 'Fog', 'PerspectiveCamera', 'WebGLRenderer', 'Group', 'Mesh',
  'BoxGeometry', 'CylinderGeometry', 'ConeGeometry', 'PlaneGeometry', 'SphereGeometry',
  'MeshLambertMaterial', 'MeshBasicMaterial', 'HemisphereLight', 'DirectionalLight',
  'Raycaster', 'Vector2', 'Vector3', 'SRGBColorSpace', 'PCFSoftShadowMap',
];

const entry = `import { ${NAMES.join(', ')} } from 'three';
globalThis.THREE = Object.freeze({ ${NAMES.join(', ')}, REVISION: ${JSON.stringify(PKG.version)} });`;

const result = await build({
  stdin: { contents: entry, resolveDir: import.meta.dirname, loader: 'js' },
  bundle: true, minify: true, format: 'iife', target: 'es2019', write: false,
  legalComments: 'none',
});
const banner = `/* three.js ${PKG.version} (the classes LEDGER's 3D world uses) | MIT License | https://github.com/mrdoob/three.js/blob/dev/LICENSE | built by tools/vendor-three.mjs */\n`;
let code = banner + result.outputFiles[0].text;
/* the bundle sits inside a <script> element; a closing tag inside it would end
   the element early */
if (/<\/script/i.test(code)) code = code.replace(/<\/script/gi, '<\\/script');

const moduleText = '/* generated by tools/vendor-three.mjs from three-world.js: the same text, importable */\n' +
  'export default ' + JSON.stringify(code) + ';\n';

if (process.argv.includes('--check')) {
  const read = (f) => fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '';
  if (read(OUT) !== code || read(OUT_MODULE) !== moduleText) {
    console.log('three-world.js is stale: run node tools/vendor-three.mjs'); process.exit(1);
  }
  console.log('three-world.js   : current · three ' + PKG.version + ' · ' + code.length + ' bytes');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, code);
  fs.writeFileSync(OUT_MODULE, moduleText);
  console.log('three-world.js   : written · three ' + PKG.version + ' · ' + code.length + ' bytes (+ the importable copy)');
}
